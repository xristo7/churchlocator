import {build} from 'esbuild';
import {cp,mkdir,readFile,writeFile} from 'node:fs/promises';
import {createRequire} from 'node:module';
import {dirname,join} from 'node:path';
await mkdir('public/vendor/live',{recursive:true});
await build({stdin:{contents:"import RealtimeKitClient from '@cloudflare/realtimekit'; window.RealtimeKitClient=RealtimeKitClient;",resolveDir:process.cwd()},bundle:true,minify:true,format:'iife',platform:'browser',outfile:'public/vendor/live/realtimekit.js',legalComments:'eof'});
await cp('node_modules/@cloudflare/realtimekit-ui/dist/esm','public/vendor/live/ui',{recursive:true});
await cp('node_modules/hls.js/dist/hls.min.js','public/vendor/live/hls.min.js');
for(const [name,path] of [['realtimekit','node_modules/@cloudflare/realtimekit/LICENSE.txt'],['realtimekit-ui','node_modules/@cloudflare/realtimekit-ui/LICENSE'],['hls','node_modules/hls.js/LICENSE'],['uuid','node_modules/@cloudflare/realtimekit/node_modules/uuid/LICENSE.md']]) {
  try{await writeFile('public/vendor/live/'+name+'-LICENSE.txt',await readFile(path));}catch{ /* Some provider packages publish their license in package metadata. */ }
}
let uuidDirectory=dirname(createRequire(import.meta.resolve('@cloudflare/realtimekit')).resolve('uuid'));
for(let depth=0;depth<4;depth++,uuidDirectory=dirname(uuidDirectory)){
  try{await writeFile('public/vendor/live/uuid-LICENSE.txt',await readFile(join(uuidDirectory,'LICENSE.md')));break;}catch{}
}
await writeFile('public/vendor/live/VERSIONS.txt','RealtimeKit Core 2.0.2; RealtimeKit UI 2.0.2; hls.js 1.7.3. Generated by tools/build-live-assets.mjs.\n');
